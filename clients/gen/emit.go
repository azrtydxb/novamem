package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strings"
	"text/template"
)

// Options drive one generator run.
type Options struct {
	Spec, Routes, Templates, Out string
	// Langs, when set, limits the run to templates whose directive names
	// one of these languages.
	Langs []string
}

// directive is the first line of every template:
// {{/* lang: <lang> out: <path relative to Out> */}} (or the trimming form "*/ -}}")
var directive = regexp.MustCompile(`^\{\{/\* lang: (\S+) out: (\S+) \*/ ?-?\}\}`)

type rendered struct {
	path string // relative to Out
	body []byte
}

func render(opts Options) ([]rendered, error) {
	model, err := BuildModel(opts.Spec, opts.Routes)
	if err != nil {
		return nil, err
	}
	files, err := filepath.Glob(filepath.Join(opts.Templates, "*.tmpl"))
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	funcs := template.FuncMap{
		"pascal": pascal, "camel": camel, "snake": snake, "upperSnake": upperSnake,
		"wire":       func(f Field) string { return f.Wire },
		"join":       strings.Join,
		"pyident":    pyident,
		"rustident":  rustident,
		"methodName": func(m string) string { _, after, _ := strings.Cut(m, "."); return after },
		"className":  func(m string) string { before, _, _ := strings.Cut(m, "."); return before },
	}
	out := []rendered{}
	for _, f := range files {
		src, err := os.ReadFile(f)
		if err != nil {
			return nil, err
		}
		m := directive.FindSubmatch(src)
		if m == nil {
			return nil, fmt.Errorf("%s: first line must be {{/* lang: <lang> out: <path> */}}", f)
		}
		lang, path := string(m[1]), string(m[2])
		if len(opts.Langs) > 0 && !slices.Contains(opts.Langs, lang) {
			continue
		}
		t, err := template.New(filepath.Base(f)).Funcs(funcs).Parse(string(src))
		if err != nil {
			return nil, err
		}
		var buf bytes.Buffer
		if err := t.Execute(&buf, model); err != nil {
			return nil, fmt.Errorf("%s: %w", f, err)
		}
		body := bytes.ReplaceAll(buf.Bytes(), []byte("\r\n"), []byte("\n"))
		body = append(bytes.TrimRight(body, "\n"), '\n')
		out = append(out, rendered{path: path, body: body})
	}
	// Zero templates would make -check pass while checking nothing — the
	// one outcome a drift guard must never have.
	if len(out) == 0 {
		return nil, fmt.Errorf("no templates in %s match langs %v", opts.Templates, opts.Langs)
	}
	return out, nil
}

// header marks every file the generator writes; Check uses it to find
// generated files that no template produces any more.
const header = "Code generated by clients/gen. DO NOT EDIT."

// skipDirs are build and dependency trees that never hold generated source.
var skipDirs = map[string]bool{
	".git": true, "node_modules": true, "target": true, "bin": true, "obj": true,
	".build": true, "vendor": true, "dist": true, "dist-test": true, "build": true, "__pycache__": true,
}

// orphans returns generated files under root that are not in want. The
// templates directory is never scanned: templates print the header too.
func orphans(root, templates string, want map[string]bool) ([]string, error) {
	skip, err := filepath.Abs(templates)
	if err != nil {
		return nil, err
	}
	var out []string
	err = filepath.WalkDir(root, func(p string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if abs, _ := filepath.Abs(p); skipDirs[d.Name()] || abs == skip {
				return filepath.SkipDir
			}
			return nil
		}
		rel, err := filepath.Rel(root, p)
		if err != nil || want[filepath.ToSlash(rel)] {
			return err
		}
		f, err := os.Open(p)
		if err != nil {
			return err
		}
		defer func() { _ = f.Close() }()
		head := make([]byte, 512)
		n, _ := f.Read(head)
		if bytes.Contains(head[:n], []byte(header)) {
			out = append(out, filepath.ToSlash(rel))
		}
		return nil
	})
	return out, err
}

// Run writes every template's output under opts.Out.
func Run(opts Options) error {
	files, err := render(opts)
	if err != nil {
		return err
	}
	for _, r := range files {
		p := filepath.Join(opts.Out, r.path)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, r.body, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// Check writes nothing and returns the output paths whose file on disk
// differs from what Run would write, plus (on a full run) generated files
// that no template produces any more.
func Check(opts Options) ([]string, error) {
	files, err := render(opts)
	if err != nil {
		return nil, err
	}
	var stale []string
	want := map[string]bool{}
	for _, r := range files {
		want[r.path] = true
		have, err := os.ReadFile(filepath.Join(opts.Out, r.path))
		if err != nil || !bytes.Equal(have, r.body) {
			stale = append(stale, r.path)
		}
	}
	// A template that was renamed or removed leaves its old output behind.
	// Only a full run knows every file that should exist.
	if len(opts.Langs) == 0 {
		orphaned, err := orphans(opts.Out, opts.Templates, want)
		if err != nil {
			return nil, err
		}
		stale = append(stale, orphaned...)
	}
	sort.Strings(stale)
	return stale, nil
}
